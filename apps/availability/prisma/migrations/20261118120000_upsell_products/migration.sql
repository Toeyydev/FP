-- Tour Upsell — product configuration (PR2).
--
-- Route extensions also lose what they could never use: a fixed cost, an incentive, a
-- validity period (no service-approval lifecycle exists for them).
--
-- Adds the third product type, JOIN_SOURCE_TOUR (Three Temples on-site): a walk-in seat
-- sold by the guide on their OWN T-001 / T-002 job. It creates a Booking on that existing
-- job and never a new job; the guest pays the guide cash only; there is no fixed cost and
-- no incentive; the guide remits every baht by bank transfer; and its booking may share a
-- job with OTA guests — the only product allowed to (owner, 18 Nov 2026).
--
-- The tables are still empty in production when this runs (PR1, a7a7946). Every feature
-- switch stays off; nothing here sells anything.
--
-- A product's type lives on UpsellProduct and its rules on UpsellProductVersion, so a CHECK
-- cannot compare them: the per-type rules are a trigger on the version, and the type itself
-- can never change once set. Trigger errors carry the prefix UPSELL_.

-- AlterTable (as generated by prisma migrate diff)
ALTER TABLE "UpsellProductVersion" ADD COLUMN     "allowsOtaMix" BOOLEAN NOT NULL DEFAULT false,
ADD COLUMN     "eligibleSourceTourIds" TEXT[] DEFAULT ARRAY[]::TEXT[],
ADD COLUMN     "remittanceMethod" TEXT NOT NULL DEFAULT 'ANY';

-- ─── CHECK constraints ────────────────────────────────────────────────────────────────────

ALTER TABLE "UpsellProduct" DROP CONSTRAINT "UpsellProduct_type_check";
ALTER TABLE "UpsellProduct" ADD CONSTRAINT "UpsellProduct_type_check"
  CHECK ("productType" IN ('ROUTE_EXTENSION', 'NEW_TOUR', 'JOIN_SOURCE_TOUR'));

-- A booking is filed under a tour: a new tour names its own; a seat on an existing job takes
-- the tour of the job it joins, which must be one of the eligible tours.
ALTER TABLE "UpsellProductVersion" DROP CONSTRAINT "UpsellProductVersion_booking_needs_tour_check";
ALTER TABLE "UpsellProductVersion"
  ADD CONSTRAINT "UpsellProductVersion_booking_needs_tour_check"
    CHECK (NOT "createsNewBooking" OR "serviceTourId" IS NOT NULL OR cardinality("eligibleSourceTourIds") > 0),
  -- Prisma declares a list column nullable; an absent list is never a meaningful answer here.
  ADD CONSTRAINT "UpsellProductVersion_eligible_tours_check"
    CHECK ("eligibleSourceTourIds" IS NOT NULL AND array_position("eligibleSourceTourIds", NULL) IS NULL),
  ADD CONSTRAINT "UpsellProductVersion_remittance_method_check"
    CHECK ("remittanceMethod" IN ('ANY', 'BANK_TRANSFER'));

-- ─── Triggers ─────────────────────────────────────────────────────────────────────────────

-- A product's type decides which rules its versions follow, so it is fixed at creation.
CREATE FUNCTION upsell_product_type_frozen() RETURNS trigger AS $$
BEGIN
  IF NEW."productType" IS DISTINCT FROM OLD."productType" THEN
    RAISE EXCEPTION 'UPSELL_PRODUCT_TYPE_FROZEN: product % is %; its type never changes', OLD."productCode", OLD."productType";
  END IF;
  RETURN NEW;
END $$ LANGUAGE plpgsql;
CREATE TRIGGER upsell_product_type_frozen BEFORE UPDATE ON "UpsellProduct"
  FOR EACH ROW EXECUTE FUNCTION upsell_product_type_frozen();

-- The rules each product type's versions must follow. Checked on every insert and update,
-- so a version can neither be created nor edited into a shape its type does not allow.
CREATE FUNCTION upsell_product_version_type_rules() RETURNS trigger AS $$
DECLARE
  t text;
  bad text := NULL;
BEGIN
  SELECT "productType" INTO t FROM "UpsellProduct" WHERE "id" = NEW."productId";

  IF t = 'JOIN_SOURCE_TOUR' THEN
    IF NEW."allowedPaymentMethods" IS DISTINCT FROM ARRAY['CASH']::text[] THEN bad := 'is paid in cash to the guide only';
    ELSIF NEW."pricingBasis" <> 'PER_GUEST' THEN bad := 'is priced per guest';
    ELSIF NOT NEW."createsNewBooking" OR NEW."createsNewJob" OR NEW."serviceTourId" IS NOT NULL THEN
      bad := 'creates a booking on the guide''s existing job, never a new job or a tour of its own';
    ELSIF cardinality(NEW."eligibleSourceTourIds") = 0 THEN bad := 'needs at least one eligible tour';
    -- The owner's list (18 Nov 2026). A settings page may narrow it; nothing may widen it.
    ELSIF NOT (NEW."eligibleSourceTourIds" <@ ARRAY['T-001', 'T-002']::text[]) THEN bad := 'joins only T-001 or T-002';
    ELSIF EXISTS (SELECT 1 FROM unnest(NEW."eligibleSourceTourIds") x WHERE btrim(x) = '')
       OR cardinality(NEW."eligibleSourceTourIds") <> (SELECT count(DISTINCT x) FROM unnest(NEW."eligibleSourceTourIds") x) THEN
      bad := 'lists each eligible tour once, by id';
    ELSIF NOT NEW."allowsOtaMix" THEN bad := 'joins jobs that carry OTA guests';
    ELSIF NEW."remittanceMethod" <> 'BANK_TRANSFER' THEN bad := 'is remitted by bank transfer';
    ELSIF NEW."fixedCostPerGuestSatang" <> 0 OR NEW."fixedCostBasis" IS NOT NULL OR NEW."fixedCostCategory" IS NOT NULL THEN
      bad := 'has no fixed cost';
    ELSIF NEW."incentivePerGuestSatang" <> 0 OR NEW."incentiveTrigger" <> 'NONE' THEN bad := 'has no incentive';
    ELSIF NEW."serviceScope" <> 'EXISTING_GUIDE' THEN bad := 'is served by the guide who sold it';
    ELSIF NEW."capacityGroupKey" IS NOT NULL OR NEW."serviceValidityDays" IS NOT NULL OR NEW."checkoutLinkExpiryMinutes" IS NOT NULL THEN
      bad := 'is used on the job it was sold on — no seat group, validity period or payment link';
    END IF;
  ELSE
    -- Only a seat on an existing job joins one, mixes with OTA guests, or fixes the remittance.
    IF cardinality(NEW."eligibleSourceTourIds") <> 0 THEN bad := 'has no eligible source tours (JOIN_SOURCE_TOUR only)';
    ELSIF NEW."allowsOtaMix" THEN bad := 'never shares a job with OTA guests (JOIN_SOURCE_TOUR only)';
    ELSIF NEW."remittanceMethod" <> 'ANY' THEN bad := 'leaves the remittance method open (JOIN_SOURCE_TOUR only)';
    ELSIF t = 'ROUTE_EXTENSION' AND (NEW."createsNewBooking" OR NEW."createsNewJob") THEN
      bad := 'stays on the source job: no new booking or job';
    -- A route extension is delivered on the job it was sold on. It has no service report or
    -- approval of its own, so nothing could ever earn a fixed cost or an incentive on it, and
    -- nothing could expire: none of them may be set.
    ELSIF t = 'ROUTE_EXTENSION' AND (NEW."fixedCostPerGuestSatang" <> 0 OR NEW."fixedCostBasis" IS NOT NULL OR NEW."fixedCostCategory" IS NOT NULL) THEN
      bad := 'has no fixed cost';
    ELSIF t = 'ROUTE_EXTENSION' AND (NEW."incentivePerGuestSatang" <> 0 OR NEW."incentiveTrigger" <> 'NONE') THEN
      bad := 'has no incentive';
    ELSIF t = 'ROUTE_EXTENSION' AND (NEW."serviceValidityDays" IS NOT NULL OR NEW."checkoutLinkExpiryMinutes" IS NOT NULL
                                    OR NEW."capacityGroupKey" IS NOT NULL OR NEW."serviceScope" <> 'EXISTING_GUIDE') THEN
      bad := 'is used on the job it was sold on, by its guide — no validity period, payment link or seat group';
    ELSIF t = 'NEW_TOUR' AND NOT (NEW."createsNewBooking" AND NEW."createsNewJob" AND NEW."serviceTourId" IS NOT NULL) THEN
      bad := 'creates a new booking and job on its own tour';
    END IF;
  END IF;

  IF bad IS NOT NULL THEN
    RAISE EXCEPTION 'UPSELL_PRODUCT_RULE: a % product %', t, bad;
  END IF;
  RETURN NEW;
END $$ LANGUAGE plpgsql;
CREATE TRIGGER upsell_product_version_type_rules BEFORE INSERT OR UPDATE ON "UpsellProductVersion"
  FOR EACH ROW EXECUTE FUNCTION upsell_product_version_type_rules();
